-- 4?? SIMULAR EL AGRUPAMIENTO QUE HACE EL CÓDIGO C#
-- ???????????????????????????????????????????????????????????????????
WITH PartiddasConCodigo AS (
    SELECT 
        Codigo,
        Padre,
        Etapa,
        Partida,
        CASE 
            -- Intentar convertir Codigo a entero
            WHEN TRY_CAST(Codigo AS INT) IS NOT NULL THEN TRY_CAST(Codigo AS INT)
            
            -- Si no hay Codigo, usar diccionario de orden
            WHEN Padre = 'Preliminares' THEN 1
            WHEN Padre IN ('Cimentación', 'Cimentacion') THEN 2
            WHEN Padre IN ('Estructura', 'Losas', 'Muros') THEN 3
            WHEN Padre IN ('Inst. Hidraulica', 'Inst. Hidráulica', 'Instalacion Hidraulica',
                          'Inst. Sanitaria', 'Gas LP', 'Inst. Hidraulica - Sanitaria - Gas LP') THEN 4
            WHEN Padre IN ('Inst. Electrica', 'Inst. Eléctrica', 'Instalacion Electrica') THEN 5
            WHEN Padre IN ('Albañilería', 'Albanileria') THEN 6
            WHEN Padre IN ('Acabados', 'Acabados Exteriores', 'Acabados Interiores') THEN 7
            WHEN Padre IN ('Herrería, Aluminio y Vidrio', 'Herreria, Aluminio y Vidrio') THEN 8
            WHEN Padre IN ('Carpintería', 'Carpinteria', 'Cerrajería', 'Cerrajeria') THEN 9
            WHEN Padre IN ('Muebles', 'Accesorios', 'Muebles y Accesorios') THEN 10
            WHEN Padre IN ('Inst especiales y Obra Exterior', 'Limpieza e Instalaciones especiales') THEN 11
            WHEN Padre IN ('Urbanización', 'Urbanizacion') THEN 12
            
            -- Fallback: Sin Codigo y sin match en diccionario
            ELSE 999
        END as [CodigoNumerico]
    FROM PresupuestoObra
)
SELECT 
    CodigoNumerico,
    COUNT(*) as [Intentos de Crear Categoria],
    COUNT(DISTINCT Padre) as [Padres Diferentes],
    STRING_AGG(DISTINCT Padre, ', ') as [Nombres de Padre],
    CASE 
        WHEN COUNT(DISTINCT Padre) > 1 THEN '?? CONFLICTO: Múltiples padres con mismo código'
        WHEN COUNT(*) > 50 THEN '?? ADVERTENCIA: Muchas partidas en una categoría'
        ELSE '? OK'
    END as [Estado]
FROM PartiddasConCodigo
GROUP BY CodigoNumerico
ORDER BY CodigoNumerico;

