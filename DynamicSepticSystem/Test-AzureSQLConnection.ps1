# Script de Verificación Rápida de Azure SQL Database
# Para uso desde PowerShell - CALANDRIA RESIDENCIAL

Write-Host "?????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?  VERIFICACIÓN RÁPIDA - Azure SQL Database            ?" -ForegroundColor Cyan
Write-Host "?????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Variables de configuración
$serverName = "calandria-sqlserver.database.windows.net"
$databaseName = "CALANDRIA"
$userId = "CloudSA9f45f232"
$timeout = 30

Write-Host "?? Configuración:" -ForegroundColor Yellow
Write-Host "  • Servidor: $serverName" -ForegroundColor Gray
Write-Host "  • Base de datos: $databaseName" -ForegroundColor Gray
Write-Host "  • Usuario: $userId" -ForegroundColor Gray
Write-Host ""

# ?????????????????????????????????????????????????????????????????
# 1. VERIFICAR CONECTIVIDAD DE RED
# ?????????????????????????????????????????????????????????????????
Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray
Write-Host "?? PASO 1: Verificando conectividad de red..." -ForegroundColor Cyan
Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray

# Obtener IP pública
Write-Host "?? Obteniendo tu IP pública..." -ForegroundColor Gray
try {
    $publicIP = (Invoke-WebRequest -uri "https://api.ipify.org" -UseBasicParsing -TimeoutSec 5).Content
    Write-Host "  ? Tu IP pública: $publicIP" -ForegroundColor Green
} catch {
    Write-Host "  ? No se pudo obtener IP pública (sin Internet?)" -ForegroundColor Red
    $publicIP = "N/D"
}

Write-Host ""

# Ping a Azure SQL Server
Write-Host "?? Probando ping a Azure SQL Server..." -ForegroundColor Gray
try {
    $pingResult = Test-Connection -ComputerName $serverName -Count 2 -Quiet
    if ($pingResult) {
        Write-Host "  ? Ping exitoso a $serverName" -ForegroundColor Green
    } else {
        Write-Host "  ? No se puede hacer ping al servidor" -ForegroundColor Red
        Write-Host "  ?? Esto es normal si el firewall bloquea ICMP" -ForegroundColor Yellow
    }
} catch {
    Write-Host "  ??  Error al hacer ping: $($_.Exception.Message)" -ForegroundColor Yellow
}

Write-Host ""

# ?????????????????????????????????????????????????????????????????
# 2. VERIFICAR PUERTO 1433 (SQL Server)
# ?????????????????????????????????????????????????????????????????
Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray
Write-Host "?? PASO 2: Verificando puerto 1433 (SQL)..." -ForegroundColor Cyan
Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray

try {
    $tcpClient = New-Object System.Net.Sockets.TcpClient
    $asyncResult = $tcpClient.BeginConnect($serverName, 1433, $null, $null)
    $wait = $asyncResult.AsyncWaitHandle.WaitOne(5000, $false)
    
    if ($wait) {
        $tcpClient.EndConnect($asyncResult)
        Write-Host "  ? Puerto 1433 ABIERTO - SQL Server accesible" -ForegroundColor Green
        $tcpClient.Close()
    } else {
        Write-Host "  ? Puerto 1433 CERRADO o bloqueado por firewall" -ForegroundColor Red
        Write-Host "  ?? Agrega tu IP ($publicIP) al firewall de Azure" -ForegroundColor Yellow
    }
} catch {
    Write-Host "  ? No se puede conectar al puerto 1433" -ForegroundColor Red
    Write-Host "  ?? Verifica firewall de Azure y Windows" -ForegroundColor Yellow
} finally {
    if ($tcpClient) {
        $tcpClient.Close()
    }
}

Write-Host ""

# ?????????????????????????????????????????????????????????????????
# 3. PROBAR CONEXIÓN SQL
# ?????????????????????????????????????????????????????????????????
Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray
Write-Host "???  PASO 3: Probando conexión a SQL Database..." -ForegroundColor Cyan
Write-Host "?????????????????????????????????????????????????????" -ForegroundColor DarkGray

# Solicitar contraseña de forma segura
$password = Read-Host "Ingresa la contraseña para $userId" -AsSecureString
$BSTR = [System.Runtime.InteropServices.Marshal]::SecureStringToBSTR($password)
$plainPassword = [System.Runtime.InteropServices.Marshal]::PtrToStringAuto($BSTR)

# Connection string
$connectionString = "Server=tcp:$serverName,1433;Initial Catalog=$databaseName;Persist Security Info=False;User ID=$userId;Password=$plainPassword;MultipleActiveResultSets=False;Encrypt=True;TrustServerCertificate=False;Connection Timeout=$timeout;"

try {
    Write-Host "?? Intentando conectar..." -ForegroundColor Gray
    
    $connection = New-Object System.Data.SqlClient.SqlConnection
    $connection.ConnectionString = $connectionString
    
    $stopwatch = [System.Diagnostics.Stopwatch]::StartNew()
    $connection.Open()
    $stopwatch.Stop()
    
    Write-Host "  ? CONEXIÓN EXITOSA ($($stopwatch.ElapsedMilliseconds)ms)" -ForegroundColor Green
    Write-Host ""
    
    # Obtener información del servidor
    Write-Host "?? Información del servidor:" -ForegroundColor Cyan
    
    $command = $connection.CreateCommand()
    $command.CommandText = "SELECT @@VERSION AS Version, DB_NAME() AS Database, SUSER_NAME() AS User, GETDATE() AS ServerTime"
    $reader = $command.ExecuteReader()
    
    if ($reader.Read()) {
        $dbName = $reader["Database"]
        $userName = $reader["User"]
        $serverTime = $reader["ServerTime"]
        
        Write-Host "  • Base de datos: $dbName" -ForegroundColor Gray
        Write-Host "  • Usuario conectado: $userName" -ForegroundColor Gray
        Write-Host "  • Hora del servidor: $serverTime" -ForegroundColor Gray
    }
    $reader.Close()
    
    Write-Host ""
    
    # Contar tablas
    Write-Host "?? Estadísticas:" -ForegroundColor Cyan
    $command.CommandText = "SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE = 'BASE TABLE'"
    $tableCount = $command.ExecuteScalar()
    Write-Host "  • Tablas en la BD: $tableCount" -ForegroundColor Gray
    
    # Verificar tamaño de la BD
    $command.CommandText = @"
SELECT 
    SUM(reserved_page_count) * 8.0 / 1024 AS SizeMB
FROM sys.dm_db_partition_stats
"@
    $sizeMB = [math]::Round($command.ExecuteScalar(), 2)
    Write-Host "  • Tamaño de BD: $sizeMB MB" -ForegroundColor Gray
    
    $connection.Close()
    
    Write-Host ""
    Write-Host "???????????????????????????????????????????????????????" -ForegroundColor Green
    Write-Host "? TODOS LOS TESTS PASARON - Sistema funcional" -ForegroundColor Green
    Write-Host "???????????????????????????????????????????????????????" -ForegroundColor Green
    
} catch [System.Data.SqlClient.SqlException] {
    Write-Host "  ? ERROR SQL: $($_.Exception.Message)" -ForegroundColor Red
    Write-Host ""
    
    # Diagnosticar según código de error
    $errorNumber = $_.Exception.Errors[0].Number
    
    Write-Host "?? DIAGNÓSTICO:" -ForegroundColor Yellow
    switch ($errorNumber) {
        53 {
            Write-Host "  Error 53: No se puede conectar al servidor" -ForegroundColor Red
            Write-Host "  ?? Solución:" -ForegroundColor Yellow
            Write-Host "     1. Verifica que el firewall de Azure permita tu IP: $publicIP" -ForegroundColor Gray
            Write-Host "     2. Ve a: Azure Portal ? SQL Server ? Firewalls and virtual networks" -ForegroundColor Gray
        }
        18456 {
            Write-Host "  Error 18456: Login fallido" -ForegroundColor Red
            Write-Host "  ?? Solución:" -ForegroundColor Yellow
            Write-Host "     1. Verifica usuario y contraseña" -ForegroundColor Gray
            Write-Host "     2. Resetea la contraseña en Azure Portal si es necesario" -ForegroundColor Gray
        }
        40613 {
            Write-Host "  Error 40613: Base de datos no disponible" -ForegroundColor Red
            Write-Host "  ?? Solución:" -ForegroundColor Yellow
            Write-Host "     1. Verifica el estado de la BD en Azure Portal" -ForegroundColor Gray
            Write-Host "     2. Espera unos minutos si hay mantenimiento" -ForegroundColor Gray
        }
        4060 {
            Write-Host "  Error 4060: No se puede abrir la base de datos" -ForegroundColor Red
            Write-Host "  ?? Solución:" -ForegroundColor Yellow
            Write-Host "     1. Verifica que el nombre de la BD sea correcto: $databaseName" -ForegroundColor Gray
        }
        default {
            Write-Host "  Error $errorNumber (no categorizado)" -ForegroundColor Red
            Write-Host "  ?? Busca el error en: https://docs.microsoft.com/sql/relational-databases/errors-events/" -ForegroundColor Yellow
        }
    }
    
} catch {
    Write-Host "  ? ERROR GENERAL: $($_.Exception.Message)" -ForegroundColor Red
} finally {
    if ($connection -and $connection.State -eq 'Open') {
        $connection.Close()
    }
    # Limpiar contraseña de memoria
    [System.Runtime.InteropServices.Marshal]::ZeroFreeBSTR($BSTR)
}

Write-Host ""
Write-Host "???????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Script completado - $(Get-Date -Format 'dd/MM/yyyy HH:mm:ss')" -ForegroundColor Cyan
Write-Host "???????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""
Write-Host "?? Presiona cualquier tecla para salir..." -ForegroundColor Yellow
$null = $Host.UI.RawUI.ReadKey("NoEcho,IncludeKeyDown")
